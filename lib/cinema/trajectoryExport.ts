/**
 * Trajectory export — convert Waypoint[] into a YAML scene-fragment that
 * can be pasted directly into a case-study mdx `scenes:` array.
 *
 * Each consecutive pair (waypoint i, i+1) becomes one scene block:
 *   - camera.from = waypoint[i].position
 *   - camera.to   = waypoint[i+1].position
 *   - camera.lookAt = waypoint[i].lookAt
 *   - mapState   = waypoint[i].mapState (omit overlay if "none")
 *   - rhythm     = "still" if from===to, else "tracking"
 *
 * Single-waypoint trajectories: emit one still scene with from===to.
 *
 * Author placeholders (left as TODO in YAML):
 *   - id: scene-X-Y-PLACEHOLDER
 *   - kind: ???
 *   - emphasis: ???
 *   - enter / exit: fade / fade defaults
 */

import type { Waypoint } from "./trajectoryTypes";

const INDENT = "          "; // 10 spaces — matches `scenes:` array item indent in mdx

function vec3(v: readonly [number, number, number]): string {
  return `[${v.map(formatNum).join(", ")}]`;
}

function formatNum(n: number): string {
  // Strip trailing zeros, keep up to 3 decimals
  const fixed = n.toFixed(3);
  const trimmed = fixed.replace(/\.?0+$/, "");
  return trimmed === "-0" ? "0" : trimmed;
}

function eq3(
  a: readonly [number, number, number],
  b: readonly [number, number, number],
): boolean {
  return a[0] === b[0] && a[1] === b[1] && a[2] === b[2];
}

function rhythmFor(
  from: readonly [number, number, number],
  to: readonly [number, number, number],
): "still" | "tracking" {
  return eq3(from, to) ? "still" : "tracking";
}

/**
 * Serialize one scene block. `index` is the 1-based scene index used in the
 * placeholder id (`scene-X-Y-PLACEHOLDER`). `from` and `to` come from waypoint
 * pairs; `mapState` and `lookAt` from the FROM waypoint.
 */
function sceneBlock(
  from: Waypoint,
  to: Waypoint,
  index: number,
): string {
  const lines: string[] = [];
  const inner = INDENT + "  "; // 12 spaces — fields inside scene
  const indent = inner;

  lines.push(`${INDENT}- id: scene-PLACEHOLDER-${index}   # ⚠️ rename`);
  lines.push(`${indent}kind: title   # ⚠️ author fills (title / lead / body-section / pull-quote / data-hit)`);
  lines.push(`${indent}rhythm: ${rhythmFor(from.position, to.position)}`);
  lines.push(`${indent}emphasis: standard   # ⚠️ author tunes (brief / standard / dwell / linger)`);
  lines.push(`${indent}camera:`);
  lines.push(`${indent}  from: ${vec3(from.position)}`);
  lines.push(`${indent}  to: ${vec3(to.position)}`);
  lines.push(`${indent}  lookAt: ${vec3(from.lookAt)}`);
  lines.push(`${indent}enter: fade`);
  lines.push(`${indent}exit: fade`);
  lines.push(`${indent}mapState:`);
  lines.push(`${indent}  mode: ${from.mapState.mode}`);
  lines.push(`${indent}  dim: ${formatNum(from.mapState.dim)}`);
  if (from.mapState.overlay !== "none") {
    lines.push(`${indent}  overlay: ${from.mapState.overlay}`);
  }

  return lines.join("\n");
}

export function exportToYaml(waypoints: Waypoint[]): string {
  if (waypoints.length === 0) {
    return "# (no waypoints recorded)";
  }

  const blocks: string[] = [];
  blocks.push("# ⚠️ Generated by /dev/trajectory — paste into mdx scenes:");
  blocks.push("# Each block is one scene. Rename ids, fill kind & emphasis.");
  blocks.push("");

  if (waypoints.length === 1) {
    // Single waypoint = still scene with from === to
    blocks.push(sceneBlock(waypoints[0], waypoints[0], 1));
  } else {
    for (let i = 0; i < waypoints.length - 1; i++) {
      blocks.push(sceneBlock(waypoints[i], waypoints[i + 1], i + 1));
      blocks.push("");
    }
  }

  return blocks.join("\n");
}

/**
 * Total expected duration (seconds) of the trajectory — sum of
 * durationToNext, ignoring the last waypoint.
 */
export function totalDuration(waypoints: Waypoint[]): number {
  let s = 0;
  for (let i = 0; i < waypoints.length; i++) {
    s += waypoints[i].durationToNext;
  }
  return s;
}
